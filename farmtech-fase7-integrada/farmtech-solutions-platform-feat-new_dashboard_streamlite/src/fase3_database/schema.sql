CREATE TABLE SENSORES_FARMTECH_IOT (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ts_leitura TIMESTAMP NOT NULL,
    umidade NUMBER(6,2) NOT NULL,
    ph NUMBER(5,2) NOT NULL,
    nitrogenio NUMBER(9,2) NOT NULL,
    fosforo NUMBER(9,2) NOT NULL,
    potassio NUMBER(9,2) NOT NULL,
    chuva NUMBER(1) NOT NULL,
    irrigacao NUMBER(1) NOT NULL,
    CONSTRAINT uq_farmtech_ts UNIQUE (ts_leitura),
    CONSTRAINT ck_farmtech_chuva CHECK (chuva IN (0, 1)),
    CONSTRAINT ck_farmtech_irrigacao CHECK (irrigacao IN (0, 1))
);

CREATE TABLE DETECCOES_FARMTECH (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    execucao_id VARCHAR2(36) NOT NULL,
    ts_deteccao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    arquivo_imagem VARCHAR2(255) NOT NULL,
    classe VARCHAR2(80) NOT NULL,
    confianca NUMBER(6,5) NOT NULL,
    x1 NUMBER(10) NOT NULL,
    y1 NUMBER(10) NOT NULL,
    x2 NUMBER(10) NOT NULL,
    y2 NUMBER(10) NOT NULL,
    modelo VARCHAR2(255) NOT NULL
);
