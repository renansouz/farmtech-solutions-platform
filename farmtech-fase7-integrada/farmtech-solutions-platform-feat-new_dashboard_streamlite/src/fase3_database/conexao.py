"""Conexão Oracle e criação idempotente das tabelas da FarmTech (Fases 3 e 6)."""
from __future__ import annotations

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


class ConfiguracaoOracleError(RuntimeError):
    """Configuração insuficiente para utilizar o Oracle real."""


def carregar_ambiente() -> None:
    from dotenv import load_dotenv
    load_dotenv(ROOT / ".env")


def credenciais_configuradas() -> bool:
    carregar_ambiente()
    usuario = os.getenv("ORACLE_USER", "").strip()
    senha = os.getenv("ORACLE_PASSWORD", "").strip()
    return bool(usuario and senha and not usuario.startswith("RMxxxx")
                and senha != "sua_senha")


def conectar_oracle():
    """Abre uma conexão real; nunca simula sucesso nem armazena credenciais no código."""
    carregar_ambiente()
    if not credenciais_configuradas():
        raise ConfiguracaoOracleError(
            "Configure ORACLE_USER e ORACLE_PASSWORD no .env para conectar ao Oracle."
        )

    import oracledb  # Import tardio para permitir validação local sem driver.

    host = os.getenv("ORACLE_HOST", "oracle.fiap.com.br")
    porta = int(os.getenv("ORACLE_PORT", "1521"))
    servico = os.getenv("ORACLE_SERVICE", "ORCL")
    dsn = oracledb.makedsn(host, porta, service_name=servico)
    return oracledb.connect(
        user=os.environ["ORACLE_USER"],
        password=os.environ["ORACLE_PASSWORD"],
        dsn=dsn,
    )


DDL_SENSORES = """
CREATE TABLE SENSORES_FARMTECH_IOT (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ts_leitura TIMESTAMP NOT NULL,
    umidade NUMBER(6,2) NOT NULL,
    ph NUMBER(5,2) NOT NULL,
    nitrogenio NUMBER(9,2) NOT NULL,
    fosforo NUMBER(9,2) NOT NULL,
    potassio NUMBER(9,2) NOT NULL,
    chuva NUMBER(1) NOT NULL,
    irrigacao NUMBER(1) NOT NULL,
    CONSTRAINT uq_farmtech_ts UNIQUE (ts_leitura),
    CONSTRAINT ck_farmtech_chuva CHECK (chuva IN (0,1)),
    CONSTRAINT ck_farmtech_irrigacao CHECK (irrigacao IN (0,1))
)
"""

DDL_DETECCOES = """
CREATE TABLE DETECCOES_FARMTECH (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    execucao_id VARCHAR2(36) NOT NULL,
    ts_deteccao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    arquivo_imagem VARCHAR2(255) NOT NULL,
    classe VARCHAR2(80) NOT NULL,
    confianca NUMBER(6,5) NOT NULL,
    x1 NUMBER(10) NOT NULL,
    y1 NUMBER(10) NOT NULL,
    x2 NUMBER(10) NOT NULL,
    y2 NUMBER(10) NOT NULL,
    modelo VARCHAR2(255) NOT NULL
)
"""


def garantir_tabelas(conn, *, incluir_deteccoes: bool = True) -> list[str]:
    """Cria somente tabelas ausentes do schema conectado (Oracle 12c+)."""
    tabelas = [("SENSORES_FARMTECH_IOT", DDL_SENSORES)]
    if incluir_deteccoes:
        tabelas.append(("DETECCOES_FARMTECH", DDL_DETECCOES))
    criadas = []
    with conn.cursor() as cursor:
        for nome, ddl in tabelas:
            cursor.execute(
                "SELECT COUNT(*) FROM user_tables WHERE table_name = :nome",
                {"nome": nome},
            )
            if cursor.fetchone()[0] == 0:
                cursor.execute(ddl)
                criadas.append(nome)
    return criadas
